#!/usr/bin/env python3
"""Generate (or verify) every compiled-in firmware blob from ``firmware/``.

An RTOS image has no filesystem: a driver's ``request_firmware()`` is served
by ``components/linuxkpi/rtos/fw_registry_rtos.c`` from a table the image
fills at start-up, and the AIC8800 vendor stack downloads its five images from
arrays it is given.  Both carriers are C arrays generated from the vendor
firmware file for the chip - and those files live in this repository under
``firmware/`` (see ``firmware/README.md``).

This script is the one table: source file, request name, C symbol and the
output unit.  It replaces running ``fw-blob.py`` by hand once per chip, which
is how a clean checkout used to end up with an image that failed to link.

    # write every blob that is missing or out of date (the build does this)
    tools/rtos/fw-blobs.py --all

    # one stem, the form the make rule uses
    tools/rtos/fw-blobs.py --stem rtw8851b_fw

    # verify the generated units against firmware/ (and their headers)
    tools/rtos/fw-blobs.py --check --all

The generated units stay gitignored: they are a build product, byte-identical
to ``firmware/<path>``, and the digest in each header is the anchor.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIRMWARE = ROOT / "firmware"
FW_DIR = ROOT / "components" / "linuxkpi" / "fw"

BYTES_PER_LINE = 12

# The linuxkpi registry blobs: (stem, source under firmware/, request name,
# licence reference).  The stem is the C symbol: the array is <stem>_data and
# the unit registers as lkpi_fw_<stem>_register().
LINUXKPI = [
    ("rtl8188eufw", "rtlwifi/rtl8188eufw.bin", "rtlwifi/rtl8188eufw.bin",
     "Realtek binary redistribution terms, firmware/REALTEK-LICENCE.txt"),
    ("rtl8723bu", "rtlwifi/rtl8723bu_nic.bin", "rtlwifi/rtl8723bu_nic.bin",
     "Realtek binary redistribution terms, firmware/REALTEK-LICENCE.txt"),
    ("rtw8821c_fw", "rtw88/rtw8821c_fw.bin", "rtw88/rtw8821c_fw.bin",
     "Realtek binary redistribution terms, firmware/REALTEK-LICENCE.txt"),
    ("rtw8851b_fw", "rtw89/rtw8851b_fw-1.bin", "rtw89/rtw8851b_fw-1.bin",
     "Realtek binary redistribution terms, firmware/REALTEK-LICENCE.txt"),
    ("iwl7260_fw", "iwlwifi/iwlwifi-7260-17.ucode", "iwlwifi-7260-17.ucode",
     "Intel binary redistribution terms, firmware/INTEL-LICENCE.txt"),
]

# The AIC8800 demo stack's five images: (enum order, file, array symbol).
AIC8800 = [
    ("AIC8800_FW_PATCH_TABLE", "fw_patch_table_8800d80_u02.bin",
     "g_aic8800_fw_patch_table", 1384),
    ("AIC8800_FW_ADID", "fw_adid_8800d80_u02.bin", "g_aic8800_fw_adid", 1708),
    ("AIC8800_FW_PATCH", "fw_patch_8800d80_u02.bin", "g_aic8800_fw_patch", 32700),
    ("AIC8800_FW_PATCH_EXT0", "fw_patch_8800d80_u02_ext0.bin",
     "g_aic8800_fw_patch_ext0", 16136),
    ("AIC8800_FW_FMAC", "fmacfw_8800d80_u02.bin", "g_aic8800_fw_fmacfw", 358072),
]
AIC8800_DIR = ROOT / "wireless-drivers" / "aic8800" / "fw"
AIC8800_OUT = AIC8800_DIR / "aic8800_fw_blobs.c"


def read_source(rel: str) -> bytes:
    path = FIRMWARE / rel
    if not path.is_file():
        raise SystemExit(
            f"fw-blobs: {path} is missing; the firmware tree is part of the "
            f"repository - restore it (see firmware/README.md)")
    return path.read_bytes()


def emit_linuxkpi(stem: str, request: str, data: bytes, source: str,
                  licence: str) -> str:
    sha = hashlib.sha256(data).hexdigest()
    upper = stem.upper()
    parts = [
        "/* SPDX-License-Identifier: BSD-3-Clause */\n",
        "/*\n",
        f" * @file    fw/{stem}_blob.c\n",
        f" * @brief   The {request} firmware image, compiled in as the one blob\n",
        " *          the driver asks for by name.\n",
        " *\n",
        " * @design static data table registered by name at start-up: the target\n",
        " *         has no filesystem, so the registry is the loader and this\n",
        " *         unit is its data.  The bytes are byte-identical to\n",
        f" *         firmware/{source} sha256\n",
        f" *         {sha}\n",
        f" *         {len(data)} bytes.  License: {licence}; unmodified.\n",
        " *         GENERATED by tools/rtos/fw-blobs.py - do not edit by hand.\n",
        " */\n\n",
        '#include "../fw_registry.h"\n\n',
        f"/* {len(data)} bytes. */\n",
        f"static const unsigned char {stem}_data[] = {{\n",
    ]
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE]
        parts.append("\t" + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    parts.append("};\n\n")
    parts.append(f"#define {upper}_SIZE {len(data)}\n\n")
    parts.append(
        f"_Static_assert(sizeof({stem}_data) == {upper}_SIZE,\n"
        "\t       \"the compiled-in firmware image must have the size it was "
        "generated from\");\n\n")
    parts.append(
        f"int lkpi_fw_{stem}_register(void)\n"
        "{\n"
        f"\treturn lkpi_fw_register(\"{request}\", {stem}_data,\n"
        f"\t\t\t       sizeof({stem}_data));\n"
        "}\n")
    return "".join(parts)


def emit_aic8800() -> str:
    parts = [
        "/* GENERATED by tools/rtos/fw-blobs.py - DO NOT EDIT.\n",
        " *\n",
        " * The five AIC8800D80 U02 firmware images, compiled in as const\n",
        " * arrays and registered with aic8800_fw_set_images() by\n",
        " * aic8800_fw_blobs_register().  The bytes are Aicsemi's GPL-3.0\n",
        " * firmware (firmware/aic8800/, firmware/GPL-3.0.txt).\n",
        " */\n",
        "#include <stdint.h>\n\n",
        '#include "aic8800_fw.h"\n\n',
    ]
    for _, name, symbol, length in AIC8800:
        data = read_source(f"aic8800/{name}")
        if len(data) != length:
            raise SystemExit(
                f"fw-blobs: aic8800/{name} is {len(data)} bytes, "
                f"expected {length}")
        parts.append(f"/* {name} - sha256 {hashlib.sha256(data).hexdigest()} */\n")
        parts.append(f"static const uint8_t {symbol}[{length}u] = {{\n")
        for i in range(0, len(data), BYTES_PER_LINE):
            chunk = data[i:i + BYTES_PER_LINE]
            parts.append("    " + ",".join(f"0x{b:02x}u" for b in chunk) + ",\n")
        parts.append("};\n\n")
    table = ",\n        ".join(f"{{ {symbol}, sizeof({symbol}) }}"
                              for _, _, symbol, _ in AIC8800)
    parts.append(
        "int aic8800_fw_blobs_register(void)\n"
        "{\n"
        "    static const struct aic8800_fw_blob blobs[\n"
        "        AIC8800_FW_IMAGE_COUNT] = {\n"
        f"        {table},\n"
        "    };\n\n"
        "    return aic8800_fw_set_images(blobs);\n"
        "}\n")
    return "".join(parts)


def generate(stem: str | None) -> int:
    written = 0
    for name, source, request, licence in LINUXKPI:
        if stem and name != stem:
            continue
        data = read_source(source)
        out = FW_DIR / f"{name}_blob.c"
        text = emit_linuxkpi(name, request, data, source, licence)
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.is_file() and out.read_text() == text:
            continue
        out.write_text(text)
        print(f"fw-blobs: wrote {out.relative_to(ROOT)} "
              f"payload={len(data)} sha256={hashlib.sha256(data).hexdigest()}")
        written += 1
    if stem in (None, "aic8800"):
        AIC8800_DIR.mkdir(parents=True, exist_ok=True)
        text = emit_aic8800()
        if not AIC8800_OUT.is_file() or AIC8800_OUT.read_text() != text:
            AIC8800_OUT.write_text(text)
            print(f"fw-blobs: wrote {AIC8800_OUT.relative_to(ROOT)}")
            written += 1
    if stem and not written:
        raise SystemExit(
            f"fw-blobs: no blob named '{stem}'; known stems: "
            + ", ".join(n for n, *_ in LINUXKPI) + ", aic8800")
    return 0


ARRAY_RE = re.compile(r"static const unsigned char (\w+)_data\[\] = \{(.*?)\};",
                      re.S)
SHA_RE = re.compile(r"sha256\s*\n?\s*\*?\s*([0-9a-f]{64})")


def check(stem: str | None) -> int:
    problems: list[str] = []
    for name, source, request, _ in LINUXKPI:
        if stem and name != stem:
            continue
        path = FW_DIR / f"{name}_blob.c"
        data = read_source(source)
        if not path.is_file():
            problems.append(f"{path.relative_to(ROOT)}: missing")
            continue
        text = path.read_text()
        match = ARRAY_RE.search(text)
        if not match:
            problems.append(f"{path.relative_to(ROOT)}: no data array")
            continue
        payload = bytes(int(x, 16)
                        for x in re.findall(r"0x([0-9a-fA-F]{2})", match.group(2)))
        if payload != data:
            problems.append(
                f"{path.relative_to(ROOT)}: payload != firmware/{source} "
                f"({len(payload)} vs {len(data)} bytes)")
            continue
        if f'lkpi_fw_register("{request}"' not in text:
            problems.append(
                f"{path.relative_to(ROOT)}: does not register '{request}'")
        sha_match = SHA_RE.search(text)
        sha = hashlib.sha256(payload).hexdigest()
        if not sha_match or sha_match.group(1) != sha:
            problems.append(f"{path.relative_to(ROOT)}: header digest is not "
                            f"{sha}")
        else:
            print(f"fw-blobs: {path.relative_to(ROOT)} == firmware/{source} "
                  f"({len(payload)} bytes, sha256 {sha})")
    if stem in (None, "aic8800"):
        if not AIC8800_OUT.is_file():
            problems.append(f"{AIC8800_OUT.relative_to(ROOT)}: missing")
        else:
            text = AIC8800_OUT.read_text()
            for _, name, _, length in AIC8800:
                data = read_source(f"aic8800/{name}")
                sha = hashlib.sha256(data).hexdigest()
                if f"/* {name} - sha256 {sha} */" not in text:
                    problems.append(
                        f"{AIC8800_OUT.relative_to(ROOT)}: {name} digest is not "
                        f"{sha}")
            print(f"fw-blobs: {AIC8800_OUT.relative_to(ROOT)} checked "
                  f"({len(AIC8800)} images)")
    if problems:
        for p in problems:
            print(f"fw-blobs: FAIL {p}", file=sys.stderr)
        return 1
    print("fw-blobs: every blob matches firmware/")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--all", action="store_true",
                    help="every blob (the build's default form)")
    ap.add_argument("--stem", help="one blob stem (rtw8851b_fw, aic8800, ...)")
    ap.add_argument("--check", action="store_true",
                    help="verify the generated units against firmware/")
    args = ap.parse_args()
    if not args.all and not args.stem:
        ap.error("give --all or --stem <name>")
    return check(args.stem) if args.check else generate(args.stem)


if __name__ == "__main__":
    sys.exit(main())
