#!/usr/bin/env python3
"""Generate (or verify) the compiled-in AIC8800D80 U02 firmware set.

The AIC8800 demo stack (wireless-drivers/aic8800) loads its firmware from
five linked images registered with ``aic8800_fw_set_images()`` - see
``wireless-drivers/aic8800/aic8800_fw.h``.  This platform has no
filesystem, so the five vendor binaries are compiled in as one generated
unit, exactly the way ``fw-blob.py`` serves the linuxkpi registry blobs:
the generated file is gitignored on purpose (the bytes are the vendor's
GPL-3.0 firmware, not source), and this script plus the digests recorded
in ``docs/FIRMWARE-NOTICES.md`` are the committed half.

Usage:

    # generate (FW_DIR = a checkout of the five .bin files, e.g. the
    # CherryUSB pr/aic8800-wifi-demo tree's demo/aic8800/fw)
    tools/rtos/aic8800-fw-blobs.py --fw-dir <dir-with-five-bins> \
        --out wireless-drivers/aic8800/fw/aic8800_fw_blobs.c

    # verify an existing generated unit against the same directory
    tools/rtos/aic8800-fw-blobs.py --check \
        wireless-drivers/aic8800/fw/aic8800_fw_blobs.c --fw-dir <dir>

The generated unit's register function is pulled in by the link line's
``-Wl,-u,aic8800_fw_blobs_register`` so ``--gc-sections`` cannot drop it.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

# (enum order in aic8800_fw.h, file name, array symbol, expected length)
IMAGES = [
    ("AIC8800_FW_PATCH_TABLE", "fw_patch_table_8800d80_u02.bin",
     "g_aic8800_fw_patch_table", 1384),
    ("AIC8800_FW_ADID", "fw_adid_8800d80_u02.bin",
     "g_aic8800_fw_adid", 1708),
    ("AIC8800_FW_PATCH", "fw_patch_8800d80_u02.bin",
     "g_aic8800_fw_patch", 32700),
    ("AIC8800_FW_PATCH_EXT0", "fw_patch_8800d80_u02_ext0.bin",
     "g_aic8800_fw_patch_ext0", 16136),
    ("AIC8800_FW_FMAC", "fmacfw_8800d80_u02.bin",
     "g_aic8800_fw_fmacfw", 358072),
]

BYTES_PER_LINE = 12

HEADER = """\
/* GENERATED by tools/rtos/aic8800-fw-blobs.py - DO NOT EDIT.
 *
 * The five AIC8800D80 U02 firmware images, compiled in as const arrays
 * and registered with aic8800_fw_set_images() by
 * aic8800_fw_blobs_register().  The bytes are Aicsemi's GPL-3.0
 * firmware (see wireless-drivers/aic8800/fw/README.md and
 * docs/FIRMWARE-NOTICES.md); this file is gitignored on purpose and is
 * regenerated from the vendor files with the same script.
 */
#include <stdint.h>

#include "aic8800_fw.h"

"""


def read_image(fw_dir: Path, name: str, length: int) -> tuple[bytes, str]:
    path = fw_dir / name
    if not path.is_file():
        raise SystemExit(f"aic8800-fw-blobs: missing {path}")
    data = path.read_bytes()
    if len(data) != length:
        raise SystemExit(
            f"aic8800-fw-blobs: {path} is {len(data)} bytes, expected {length}"
        )
    return data, hashlib.sha256(data).hexdigest()


def emit_array(symbol: str, data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset : offset + BYTES_PER_LINE]
        lines.append("    " + ",".join(f"0x{b:02x}u" for b in chunk) + ",")
    body = "\n".join(lines)
    return (
        f"static const uint8_t {symbol}[{len(data)}u] = {{\n{body}\n}};\n"
    )


def generate(fw_dir: Path, out: Path) -> None:
    parts = [HEADER]
    digests = []
    for enum, name, symbol, length in IMAGES:
        data, sha = read_image(fw_dir, name, length)
        digests.append((name, len(data), sha))
        parts.append(f"/* {name} - sha256 {sha} */\n")
        parts.append(emit_array(symbol, data))
        parts.append("\n")
    table = ",\n    ".join(
        f"{{ {symbol}, sizeof({symbol}) }}"
        for _, _, symbol, _ in IMAGES
    )
    parts.append(
        "int aic8800_fw_blobs_register(void)\n"
        "{\n"
        "    static const struct aic8800_fw_blob blobs[\n"
        "        AIC8800_FW_IMAGE_COUNT] = {\n"
        f"        {table},\n"
        "    };\n"
        "\n"
        "    return aic8800_fw_set_images(blobs);\n"
        "}\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))
    for name, size, sha in digests:
        print(f"aic8800-fw-blobs: {name} {size} bytes sha256 {sha}")


def check(blob_c: Path, fw_dir: Path) -> None:
    text = blob_c.read_text()
    for _, name, _, length in IMAGES:
        data, sha = read_image(fw_dir, name, length)
        match = re.search(
            re.escape(f"/* {name} - sha256 {sha} */"), text
        )
        if match is None:
            raise SystemExit(
                f"aic8800-fw-blobs: {blob_c} does not carry {name}'s digest {sha}"
            )
        # re-extract the array and compare the bytes
        m = re.search(
            r"static const uint8_t (\w+)\[" + str(length) + r"u\] = \{(.*?)\};",
            text,
            re.S,
        )
        if m is None:
            raise SystemExit(f"aic8800-fw-blobs: array for {name} not found")
        got = bytes(
            int(tok, 16)
            for tok in re.findall(r"0x([0-9a-f]{2})u", m.group(2))
        )
        if got != data:
            raise SystemExit(f"aic8800-fw-blobs: {name} bytes differ from {fw_dir}")
    print(f"aic8800-fw-blobs: {blob_c} matches all five images in {fw_dir}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fw-dir",
        required=True,
        type=Path,
        help="directory holding the five vendor .bin files",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("wireless-drivers/aic8800/fw/aic8800_fw_blobs.c"),
        help="generated unit path (generate mode)",
    )
    parser.add_argument(
        "--check",
        type=Path,
        default=None,
        help="verify this generated unit instead of writing one",
    )
    args = parser.parse_args()
    if args.check is not None:
        check(args.check, args.fw_dir)
    else:
        generate(args.fw_dir, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
