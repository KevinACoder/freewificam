#!/usr/bin/env python3
"""Write the G2 STA passphrase header for one profile.

The QiQiJia passphrase is not kept in the repository.  A profile selects
CONFIG_STA_PSK_EXTERNAL, and this script writes

    freewificam/build/kconfig/<profile>/sta_psk.h

from the STA_PSK environment (or --psk), mode 0600.  The build directory is a
generated artifact; the header is not copied into runs/ and must not be.

Usage:
    STA_PSK='...' tools/rtos/sta-psk.py --profile rk3568-iwl7260-sta-wpa2-qiqijia
"""

from __future__ import annotations

import argparse
import json
import os
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--profile", required=True)
    ap.add_argument("--psk", default=None, help="default: STA_PSK environment")
    args = ap.parse_args()

    psk = args.psk if args.psk is not None else os.environ.get("STA_PSK")
    if not psk:
        print("sta-psk: set STA_PSK (the passphrase is not stored in the repo)",
              file=sys.stderr)
        return 2
    if len(psk) < 8 or len(psk) > 63:
        print("sta-psk: passphrase must be 8..63 characters", file=sys.stderr)
        return 2

    out = ROOT / "build" / "kconfig" / args.profile / "sta_psk.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "/* generated by tools/rtos/sta-psk.py; do not commit */\n"
        f"#define LKPI_STA_PSK {json.dumps(psk)}\n",
        encoding="ascii",
    )
    out.chmod(stat.S_IRUSR | stat.S_IWUSR)
    print(f"sta-psk: wrote {out} (0600, {len(psk)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
