#!/usr/bin/env python3
"""Generate (or verify) the compiled-in firmware blob for an RTOS image.

The RTOS bin platform has no filesystem: a driver's ``request_firmware()`` is
served by ``components/linuxkpi/rtos/fw_registry_rtos.c`` from a table that the
image fills at start-up.  The table's data is a C array generated from the
firmware file the Linux lane ships for the same chip.

Why the generated file is not in git: the bytes are Realtek's redistributable
binary, not source (see the licence reference the generator puts in the
header).  This script is the committed half: anyone can regenerate the array
from the pinned file and check that the bytes of an existing blob are the bytes
of that file.

Usage:

    # generate (the output path is gitignored on purpose)
    tools/rtos/fw-blob.py \
        --in linux-upstream/build/.../lib/firmware/rtlwifi/rtl8188eufw.bin \
        --name rtlwifi/rtl8188eufw.bin --symbol rtl8188eufw \
        --licence "Realtek binary redistribution terms, docs/FIRMWARE-NOTICES.md" \
        --out components/linuxkpi/fw/rtl8188eufw_blob.c

    # verify an existing blob (exit 1 on any difference)
    tools/rtos/fw-blob.py --check components/linuxkpi/fw/rtl8188eufw_blob.c \
        --in <the same firmware file>

The generated unit's shape mirrors ``fw/rtw8851b_fw_blob.c``: the array, a
``_Static_assert`` on the size, and ``lkpi_fw_<symbol>_register()``.  The
image's linker line carries ``-Wl,-u,lkpi_fw_<symbol>_register`` so
``--gc-sections`` cannot drop it.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

BYTES_PER_LINE = 12


def read_bytes(path: Path) -> bytes:
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"fw-blob: {path} is empty")
    return data


def c_header(out_name: str, firmware_name: str, sha256: str, size: int,
             licence: str) -> str:
    return f"""/* SPDX-License-Identifier: BSD-3-Clause */
/*
 * @file    {out_name}
 * @brief   The {firmware_name} firmware image, compiled in as the one blob
 *          the driver asks for by name.
 *
 * @design static data table registered by name at start-up, the same carrier as
 *         every other blob this project compiles in: the target has no
 *         filesystem, so the registry (fw_registry.c) is the loader and this
 *         unit is its data.  The bytes are byte-identical to the file the
 *         board's Linux lane ships for the same chip; the digest below is the
 *         anchor, and the redistribution notice sits next to this file.
 *         Source of the bytes: the Linux firmware staging for this board (same
 *         file the kernel driver loads), sha256
 *         {sha256}
 *         {size} bytes.  License: {licence}; the blob is unmodified.
 *         GENERATED by tools/rtos/fw-blob.py - do not edit by hand.
 */

#include "../fw_registry.h"

/* {size} bytes, one per line group. */
static const unsigned char {firmware_name}_data[] = {{
"""


def c_footer(firmware_name: str, size: int, request_name: str) -> str:
    upper = firmware_name.upper()
    return f"""}};

/* The image size the driver sees. */
#define {upper}_SIZE {size}

_Static_assert(sizeof({firmware_name}_data) == {upper}_SIZE,
	       "the compiled-in firmware image must have the size it was generated from");

int lkpi_fw_{firmware_name}_register(void)
{{
	return lkpi_fw_register("{request_name}", {firmware_name}_data,
			       sizeof({firmware_name}_data));
}}
"""


def generate(args: argparse.Namespace) -> int:
    data = read_bytes(Path(args.inp))
    sha = hashlib.sha256(data).hexdigest()
    if args.sha256 and args.sha256.lower() != sha:
        raise SystemExit(
            f"fw-blob: sha256 mismatch: file {sha} != expected {args.sha256}")
    if args.size and args.size != len(data):
        raise SystemExit(
            f"fw-blob: size mismatch: file {len(data)} != expected {args.size}")

    out = Path(args.out)
    out_name = out.name
    parts = [c_header(out_name, args.symbol, sha, len(data), args.licence)]
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE]
        parts.append("\t" + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    parts.append(c_footer(args.symbol, len(data), args.name))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))
    print(f"fw-blob: wrote {out} payload={len(data)} sha256={sha}")
    return 0


ARRAY_RE = re.compile(r"static const unsigned char (\w+)_data\[\] = \{(.*?)\};",
                      re.S)
SIZE_RE = re.compile(r"#define (\w+)_SIZE (\d+)")
SHA_RE = re.compile(r"sha256\n \*         ([0-9a-f]{64})")
NAME_RE = re.compile(r'lkpi_fw_register\("([^"]+)"')


def check(args: argparse.Namespace) -> int:
    blob = Path(args.check).read_text()
    match = ARRAY_RE.search(blob)
    if not match:
        raise SystemExit(f"fw-blob: no data array in {args.check}")
    symbol = match.group(1)
    body = match.group(2)
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))

    problems: list[str] = []
    size_match = SIZE_RE.search(blob)
    if not size_match or int(size_match.group(2)) != len(data):
        problems.append(
            f"size define {size_match.group(2) if size_match else 'missing'} "
            f"!= array {len(data)}")
    if size_match and size_match.group(1).lower() != symbol.lower():
        problems.append(
            f"size symbol {size_match.group(1)} != array symbol {symbol}")
    sha_match = SHA_RE.search(blob)
    sha = hashlib.sha256(data).hexdigest()
    if not sha_match:
        problems.append("no sha256 anchor in the header")
    elif sha_match.group(1) != sha:
        problems.append(f"header sha {sha_match.group(1)} != payload {sha}")

    name_match = NAME_RE.search(blob)
    if not name_match:
        problems.append("no registration name in the unit")
    elif args.name and name_match.group(1) != args.name:
        problems.append(
            f"registration name {name_match.group(1)} != {args.name}")

    if args.inp:
        source = read_bytes(Path(args.inp))
        if source != data:
            problems.append(
                f"payload differs from {args.inp} "
                f"({len(data)} vs {len(source)} bytes, sha {sha} vs "
                f"{hashlib.sha256(source).hexdigest()})")
        else:
            print(f"fw-blob: {args.check} payload == {args.inp} "
                  f"({len(data)} bytes, sha256 {sha})")
    else:
        print(f"fw-blob: {args.check} payload {len(data)} bytes sha256 {sha}")

    if problems:
        for p in problems:
            print(f"fw-blob: FAIL {p}", file=sys.stderr)
        return 1
    print(f"fw-blob: {args.check} is consistent (symbol {symbol})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--in", dest="inp", required=True,
                    help="the firmware file the Linux lane ships")
    ap.add_argument("--name", help="the name the driver asks for; the "
                                   "registration key (also checked by --check)")
    ap.add_argument("--symbol", help="the C symbol stem (array, register "
                                     "function, size define)")
    ap.add_argument("--out", help="the .c file to write")
    ap.add_argument("--licence", default="see docs/FIRMWARE-NOTICES.md",
                    help="the redistribution reference put in the header")
    ap.add_argument("--sha256", help="expected sha256 of the input (guard)")
    ap.add_argument("--size", type=int, help="expected size of the input")
    ap.add_argument("--check", help="verify an existing blob instead of "
                                    "generating one")
    args = ap.parse_args()

    if args.check:
        return check(args)

    missing = [flag for flag, value in (("--name", args.name),
                                        ("--symbol", args.symbol),
                                        ("--out", args.out)) if not value]
    if missing:
        ap.error("generation needs " + ", ".join(missing))
    if not re.fullmatch(r"[a-z0-9_]+", args.symbol):
        ap.error("--symbol must be a lowercase C identifier stem")
    return generate(args)


if __name__ == "__main__":
    sys.exit(main())