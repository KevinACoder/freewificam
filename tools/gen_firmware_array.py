#!/usr/bin/env python3
"""gen_firmware_array.py - firmware blob -> C array translation unit.

S9 FR-8 tooling: the image has no filesystem, so a firmware blob lands as
a generated C array TU registered into components/linuxkpi/fw_registry.c
(lkpi_fw_register). Usage:

    python3 tools/gen_firmware_array.py <blob.bin> <sym_prefix> <out.c>

The output carries the source path, size and sha256 in its header so the
TU is self-describing for PROVENANCE audits. Run from the repo root.
"""
import hashlib
import sys


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    blob_path, sym, out_path = sys.argv[1:]
    data = open(blob_path, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/gen_firmware_array.py - do not edit by hand.\n")
        f.write(" *\n")
        f.write(" * Source: %s\n" % blob_path)
        f.write(" * %d bytes, sha256 %s.\n" % (len(data), sha))
        f.write(" * Registered into the linuxkpi firmware registry by the\n")
        f.write(" * <sym>_register() helper below (bare image name; the\n")
        f.write(" * request path strips any directory prefix).\n")
        f.write(" */\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n\n")
        f.write("const uint8_t %s_data[] = {\n" % sym)
        for off in range(0, len(data), 16):
            chunk = data[off:off + 16]
            f.write("\t" + " ".join("0x%02x," % b for b in chunk) + "\n")
        f.write("};\n")
        f.write("const size_t %s_size = sizeof(%s_data);\n\n" % (sym, sym))
        f.write("/* fw_registry hookup (components/linuxkpi/fw_registry.c);\n")
        f.write(" * prototype kept local so the blob TU stays standalone. */\n")
        f.write("extern void lkpi_fw_register(const char *name,\n")
        f.write("    const uint8_t *data, size_t size);\n\n")
        f.write("void %s_register(void)\n{\n" % sym)
        f.write("\tlkpi_fw_register(\"%s\", %s_data, %s_size);\n}\n"
                % (blob_path.rsplit("/", 1)[-1], sym, sym))
    return 0


if __name__ == "__main__":
    sys.exit(main())
