#!/usr/bin/env python3
"""Render docs/PROFILE-MAP.md from the defconfigs.

The map is metadata: every profile stays a first-class file; the tier column
only says which ones a future CI matrix should keep running.  The tier is a
draft - BUILD-01's plan says the 34/47 split needs the owner's confirmation
before anything is removed from CI, and nothing is deleted here.

Usage:
    tools/build/profile-map.py            # write docs/PROFILE-MAP.md
    tools/build/profile-map.py --check    # fail when the file is stale
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIGS = REPO / "tests" / "board" / "rtos" / "configs"
OUT = REPO / "docs" / "PROFILE-MAP.md"

# Draft first-class set: the arms a future matrix keeps.  Grouped as the
# handoff's §4.6 skeleton; the owner confirms the list before CI changes.
FIRST_CLASS = {
    # wired netio: the throughput instrument's canonical arms
    "net-netio-raw-tx256", "net-netio-raw-tx512", "net-netio-zc",
    "net-netio-zc-txc", "net-pps", "net-loop",
    # RTL8188EUS xHCI: BA, no-BA, the watch arm, bring-up
    "rtl8xxxu-8188eu-netio-ar-ht20-ba", "rtl8xxxu-8188eu-netio-ar-ht20",
    "rtl8xxxu-8188eu-netio-watch", "rtl8xxxu-8188eu-bringup",
    # RTL8723BU EHCI: BA, no-BA, the probe arm, bring-up (the A2 arm)
    "rtl8xxxu-8723bu-netio-ar-ht20-ba", "rtl8xxxu-8723bu-netio-ar-ht20",
    "rtl8xxxu-8723bu-netio-ar-ht20-ba-probe", "rtl8xxxu-8723bu-bringup",
    # the project target: 8851BU over EHCI (the A2 arm) and xHCI
    "rtw89-8851bu-ehci-bringup", "rtw89-8851bu-bringup",
    "rtw89-8851bu-ehci", "rtw89-8851bu",
    # the other wireless lines
    "firefly-v2-rtw88-sdio", "iwlwifi-7260", "wlan-delivery",
    # buses and classes
    "usb-xhci", "usb-ehci", "pcie-nvme", "uvc",
    # firefly generations
    "firefly-v2-sdio-mci", "firefly-v2-xmac", "firefly-v1-pcie",
    # network arms kept for regression
    "net-netio-raw", "net-netio", "rtl8xxxu-8188eu-netio",
    "rtl8xxxu-8723bu-net", "wlan-obs", "wlan-ping",
}

BOARD_RE = re.compile(r"^CONFIG_BOARD_([A-Z0-9_]+)=y$", re.M)
CASES_RE = re.compile(r'^CONFIG_CASES="(.*)"$', re.M)


def read(profile: Path) -> dict[str, str]:
    text = profile.read_text()
    backend = "threadx" if "CONFIG_BACKEND_THREADX=y" in text else "freertos"
    m = BOARD_RE.search(text)
    board = {
        "RK3568_ITX": "rk3568-itx",
        "FIREFLY_V1": "firefly-v1",
        "FIREFLY_V2": "firefly-v2",
    }.get(m.group(1), m.group(1).lower()) if m else "rk3568-itx"
    image = "perf" if "CONFIG_PROFILE_PERF=y" in text else "base"
    m = CASES_RE.search(text)
    cases = m.group(1) if m else ""
    return {"backend": backend, "board": board, "image": image, "cases": cases}


def render() -> str:
    rows = []
    for path in sorted(CONFIGS.glob("*.defconfig")):
        name = path.stem
        v = read(path)
        tier = "first-class" if name in FIRST_CLASS else "archive candidate"
        rows.append((name, v["backend"], v["board"], v["image"], v["cases"], tier))

    missing = sorted(FIRST_CLASS - {r[0] for r in rows})
    if missing:
        raise SystemExit(f"profile-map: first-class profiles missing: {missing}")
    n_first = sum(1 for r in rows if r[5] == "first-class")
    n_arch = len(rows) - n_first

    lines = [
        "# Profile map",
        "",
        "The image is a function of one defconfig under",
        "`tests/board/rtos/configs/`; `tests/board/rtos/config.mk` only names the",
        "default.  This table is metadata: every profile stays a file, and the",
        "`tier` column is a draft of what a future CI matrix keeps running.  The",
        "34/47 split needs the owner's confirmation before CI changes; nothing is",
        "deleted by the BUILD-01 migration.",
        "",
        f"Generated by `tools/build/profile-map.py` from {len(rows)} defconfigs:",
        f"{n_first} first-class candidates, {n_arch} archive candidates.",
        "",
        "| Profile | Backend | Board | Image | Cases | Tier |",
        "|---|---|---|---|---|---|",
    ]
    for name, backend, board, image, cases, tier in rows:
        lines.append(f"| `{name}` | {backend} | {board} | {image} | `{cases}` | {tier} |")
    lines.append("")
    lines.append("The archive candidates are still selectable with `PROFILE=<name>`;")
    lines.append("they are not in the draft matrix only because the two wireless")
    lines.append("throughput lines and the bus/class gates cover the same code with fewer")
    lines.append("boots.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail when docs/PROFILE-MAP.md is stale")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists():
            print(f"profile-map: missing {OUT}")
            return 1
        old = OUT.read_text()
        if old != text:
            print("\n".join(difflib.unified_diff(
                old.splitlines(), text.splitlines(),
                fromfile=str(OUT), tofile=str(OUT) + " (regenerated)", lineterm="")))
            return 1
        print(f"profile-map: {OUT.relative_to(REPO)} is current")
        return 0
    OUT.write_text(text)
    print(f"profile-map: wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
