#!/usr/bin/env python3
"""Render the selected profile's source list as a CMake fragment.

The list is not re-derived here: it is what `tools/build/query.mk` prints after
including the real build Makefile with the profile's generated configuration.
The CMake side (M3) therefore consumes exactly the same component ``sources.mk``
lines the make build compiles, and any change to a component shows up in both.

Usage:
    tools/build/gen_sources.py --profile net-netio-raw-tx256
    tools/build/gen_sources.py --profile net-netio-raw-tx256 --check
    tools/build/gen_sources.py --profile net-netio-raw-tx256 --stdout

Output defaults to build/kconfig/<profile>/sources.cmake (a generated,
git-ignored file).  --check fails when the file on disk is stale.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUILD_DIR = REPO / "tests" / "board" / "rtos" / "build"
QUERY = REPO / "tools" / "build" / "query.mk"


def query_sources(profile: str, module: str = "image") -> list[str]:
    cmd = [
        "make",
        "-s",
        "-C",
        str(BUILD_DIR),
        "-f",
        str(QUERY),
        f"PROFILE={profile}",
        f"MODULE={module}",
        "SRCS",
    ]
    result = subprocess.run(cmd, text=True, capture_output=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout)
        sys.stderr.write(result.stderr)
        raise SystemExit(f"gen_sources: query failed for profile {profile!r}")
    paths = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    if not paths:
        raise SystemExit(f"gen_sources: profile {profile!r} selected no sources")
    duplicates = sorted({p for p in paths if paths.count(p) > 1})
    if duplicates:
        raise SystemExit(
            "gen_sources: duplicate source(s): " + ", ".join(duplicates)
        )
    return paths


def render(profile: str, paths: list[str]) -> str:
    lines = [
        "# Generated by tools/build/gen_sources.py; do not edit.",
        f"# profile: {profile}",
        "# Source list: tools/build/query.mk (the build Makefile's component sources.mk).",
        "set(CFG_SRCS",
    ]
    lines.extend(f'    "{path}"' for path in paths)
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", required=True)
    parser.add_argument("--module", default="image")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--stdout", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    paths = query_sources(args.profile, args.module)
    text = render(args.profile, paths)
    output = args.output or (
        REPO / "build" / "kconfig" / args.profile / "sources.cmake"
    )

    if args.stdout:
        sys.stdout.write(text)
        return 0

    if args.check:
        try:
            current = output.read_text()
        except FileNotFoundError:
            print(f"gen_sources: missing {output}", file=sys.stderr)
            return 1
        if current != text:
            print(f"gen_sources: stale {output}", file=sys.stderr)
            import difflib

            sys.stderr.writelines(
                difflib.unified_diff(
                    current.splitlines(True),
                    text.splitlines(True),
                    fromfile=str(output),
                    tofile="expected",
                )
            )
            return 1
        print(f"gen_sources: {output} up to date ({len(paths)} sources)")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text)
    print(f"gen_sources: {output} ({len(paths)} sources)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
